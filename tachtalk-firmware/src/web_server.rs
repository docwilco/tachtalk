// ── Auth helpers ─────────────────────────────────────────────────────────────

fn is_authenticated(cookie: Option<&str>, state: &State) -> bool {
    if crate::config::load_admin_password_hash().is_none() {
        return true;
    }
    if let Some(cookie) = cookie {
        if let Some(token) = auth::extract_session_token(cookie) {
            return state.sessions.contains(&token);
        }
    }
    false
}

// ── Async I/O helpers ────────────────────────────────────────────────────────

async fn read_body<T, const N: usize>(
    conn: &mut Connection<'_, T, N>,
    max: usize,
) -> Result<Vec<u8>, Error<T::Error>>
where
    T: Read + Write,
{
    let mut buf = Vec::new();
    let mut tmp = [0u8; 1024];
    loop {
        let n = conn.read(&mut tmp).await?;
        if n == 0 {
            break;
        }
        if buf.len() + n > max {
            // Drain remaining body to avoid protocol desync, then return what we have
            // (caller will reject as too large or parse error)
            buf.extend_from_slice(&tmp[..n]);
            break;
        }
        buf.extend_from_slice(&tmp[..n]);
    }
    Ok(buf)
}

async fn respond_json<T, const N: usize>(
    conn: &mut Connection<'_, T, N>,
    value: &impl serde::Serialize,
) -> Result<(), Error<T::Error>>
where
    T: Read + Write,
{
    let body = serde_json::to_vec(value).unwrap_or_default();
    conn.initiate_response(200, Some("OK"), &[("Content-Type", "application/json")])
        .await?;
    conn.write_all(&body).await?;
    Ok(())
}

async fn respond_json_status<T, const N: usize>(
    conn: &mut Connection<'_, T, N>,
    status: u16,
    reason: &str,
    value: &impl serde::Serialize,
) -> Result<(), Error<T::Error>>
where
    T: Read + Write,
{
    let body = serde_json::to_vec(value).unwrap_or_default();
    conn.initiate_response(
        status,
        Some(reason),
        &[("Content-Type", "application/json")],
    )
    .await?;
    conn.write_all(&body).await?;
    Ok(())
}

async fn respond_unauthorized<T, const N: usize>(
    conn: &mut Connection<'_, T, N>,
) -> Result<(), Error<T::Error>>
where
    T: Read + Write,
{
    conn.initiate_response(
        401,
        Some("Unauthorized"),
        &[("Content-Type", "application/json")],
    )
    .await?;
    conn.write_all(b"{\"error\":\"unauthorized\"}").await?;
    Ok(())
}

async fn respond_status<T, const N: usize>(
    conn: &mut Connection<'_, T, N>,
    status: u16,
    reason: &str,
) -> Result<(), Error<T::Error>>
where
    T: Read + Write,
{
    conn.initiate_response(status, Some(reason), &[]).await?;
    Ok(())
}

async fn respond_ok<T, const N: usize>(
    conn: &mut Connection<'_, T, N>,
) -> Result<(), Error<T::Error>>
where
    T: Read + Write,
{
    conn.initiate_response(200, Some("OK"), &[]).await?;
    Ok(())
}

// ── Socket enumeration (for debug) ──────────────────────────────────────────

fn enumerate_sockets() -> Vec<SocketInfo> {
    let mut sockets = Vec::new();

    for fd in LWIP_SOCKET_OFFSET..(LWIP_SOCKET_OFFSET + CONFIG_LWIP_MAX_SOCKETS) {
        let mut sock_type: i32 = 0;
        let mut optlen = SIZE_OF_I32;

        let result = unsafe {
            lwip_getsockopt(
                fd,
                SOL_SOCKET,
                SO_TYPE,
                std::ptr::addr_of_mut!(sock_type).cast(),
                &mut optlen,
            )
        };

        if result != 0 {
            continue;
        }

        let socket_type = match sock_type {
            x if x == SOCK_STREAM => SocketType::Tcp,
            x if x == SOCK_DGRAM => SocketType::Udp,
            x => SocketType::Unknown(x),
        };

        let local = get_socket_addr(fd, false);
        let remote = get_socket_addr(fd, true);

        sockets.push(SocketInfo {
            fd,
            socket_type,
            local,
            remote,
        });
    }

    sockets
}

fn get_socket_addr(fd: i32, peer: bool) -> Option<String> {
    let mut addr: MaybeUninit<sockaddr_in> = MaybeUninit::uninit();
    let mut addrlen = SIZE_OF_SOCKADDR_IN;

    let result = unsafe {
        if peer {
            lwip_getpeername(fd, addr.as_mut_ptr().cast::<sockaddr>(), &mut addrlen)
        } else {
            lwip_getsockname(fd, addr.as_mut_ptr().cast::<sockaddr>(), &mut addrlen)
        }
    };

    if result != 0 {
        return None;
    }

    let addr = unsafe { addr.assume_init() };

    if u32::from(addr.sin_family) != AF_INET {
        return None;
    }

    let ip = std::net::Ipv4Addr::from(u32::from_be(addr.sin_addr.s_addr));
    let port = u16::from_be(addr.sin_port);

    Some(format!("{ip}:{port}"))
}

pub fn log_sockets() {
    let sockets = enumerate_sockets();
    if sockets.is_empty() {
        warn!("No open sockets found (unexpected)");
        return;
    }

    warn!(
        "Open sockets ({}/{}):",
        sockets.len(),
        CONFIG_LWIP_MAX_SOCKETS
    );
    for s in &sockets {
        let type_str = match &s.socket_type {
            SocketType::Tcp => "TCP",
            SocketType::Udp => "UDP",
            SocketType::Unknown(t) => {
                warn!("  fd={}: type={} (unknown)", s.fd, t);
                continue;
            }
        };
        let local = s.local.as_deref().unwrap_or("?");
        let remote = s.remote.as_deref().unwrap_or("-");
        warn!("  fd={}: {} {} -> {}", s.fd, type_str, local, remote);
    }
}

