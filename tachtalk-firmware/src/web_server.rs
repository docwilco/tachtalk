    async fn handle_post_config<T: Read + Write, const N: usize>(
        &self,
        conn: &mut Connection<'_, T, N>,
        cookie: Option<&str>,
    ) -> Result<(), Error<T::Error>> {
        info!("HTTP: POST /api/config");
        if !is_authenticated(cookie, &self.state) {
            return respond_unauthorized(conn).await;
        }
        let body = read_body(conn, MAX_BODY_SIZE).await?;
        let Ok(mut new_config) = serde_json::from_slice::<Config>(&body) else {
            warn!("Invalid config JSON received");
            return respond_status(conn, 400, "Bad Request").await;
        };
        new_config.validate();

        info!(
            "Config update: led_gpio={}, {} profiles, active={}, log_level={:?}",
            new_config.led_gpio,
            new_config.profiles.len(),
            new_config.active_profile,
            new_config.log_level
        );

        let (gpios_to_reset, needs_restart) = {
            let cfg = self.state.config.lock().unwrap();
            check_restart_needed(&cfg, &new_config)
        };

        {
            let mut cfg = self.state.config.lock().unwrap();
            *cfg = new_config;
            if let Err(e) = cfg.save() {
                warn!("Failed to save config: {e}");
            }
            let num_profiles = cfg.profiles.len();
            let mut te = self.state.triggered_enabled.lock().unwrap();
            te.resize(num_profiles, false);
        }

        self.state.notify_profile_change();

        if needs_restart {
            info!("Config changed (requires restart), restarting in 2 seconds...");
            for gpio in gpios_to_reset {
                unsafe {
                    esp_idf_svc::sys::gpio_reset_pin(i32::from(gpio));
                }
            }
            conn.initiate_response(200, Some("OK"), &[("Content-Type", "application/json")])
                .await?;
            conn.write_all(b"{\"restart\":true}").await?;
            crate::thread_util::spawn_named(
                c"restart",
                4096,
                crate::thread_util::StackMemory::SpiRam,
                || {
                    std::thread::sleep(std::time::Duration::from_secs(2));
                    unsafe {
                        esp_idf_svc::sys::esp_restart();
                    }
                },
            );
        } else {
            respond_ok(conn).await?;
        }
        Ok(())
    }

