#[allow(clippy::similar_names)]
fn check_restart_needed(current: &Config, new: &Config) -> (SmallVec<u8, 4>, bool) {
    let led_changed = current.led_gpio != new.led_gpio;
    let encoder_a_changed = current.encoder_pin_a != new.encoder_pin_a;
    let encoder_b_changed = current.encoder_pin_b != new.encoder_pin_b;
    let button_changed = current.button_pin != new.button_pin;
    let status_led_changed = current.status_led_gpio != new.status_led_gpio;
    let boot_led_changed = current.boot_led_gpio != new.boot_led_gpio;
    let wifi_changed =
        current.wifi.ssid != new.wifi.ssid || current.wifi.password != new.wifi.password;
    let ip_changed = current.ip.use_dhcp != new.ip.use_dhcp
        || current.ip.ip != new.ip.ip
        || current.ip.prefix_len != new.ip.prefix_len;
    let ap_changed = current.ap_ssid != new.ap_ssid
        || current.ap_password != new.ap_password
        || current.ap_ip != new.ap_ip
        || current.ap_prefix_len != new.ap_prefix_len;

    let current_pins: SmallVec<u8, 4> = current
        .profiles
        .iter()
        .filter(|p| p.profile_type == ProfileType::Triggered && p.button_pin != 0)
        .map(|p| p.button_pin)
        .collect();
    let new_pins: SmallVec<u8, 4> = new
        .profiles
        .iter()
        .filter(|p| p.profile_type == ProfileType::Triggered && p.button_pin != 0)
        .map(|p| p.button_pin)
        .collect();
    let triggered_pins_changed = current_pins != new_pins;

    let mut gpios_to_reset = SmallVec::new();
    if led_changed {
        gpios_to_reset.push(current.led_gpio);
    }
    if encoder_a_changed && current.encoder_pin_a != 0 {
        gpios_to_reset.push(current.encoder_pin_a);
    }
    if encoder_b_changed && current.encoder_pin_b != 0 {
        gpios_to_reset.push(current.encoder_pin_b);
    }
    if button_changed && current.button_pin != 0 {
        gpios_to_reset.push(current.button_pin);
    }
    if status_led_changed && current.status_led_gpio != 0 {
        gpios_to_reset.push(current.status_led_gpio);
    }
    if boot_led_changed && current.boot_led_gpio != 0 {
        gpios_to_reset.push(current.boot_led_gpio);
    }
    if triggered_pins_changed {
        for &pin in &current_pins {
            gpios_to_reset.push(pin);
        }
    }

    let needs_restart = led_changed
        || encoder_a_changed
        || encoder_b_changed
        || button_changed
        || status_led_changed
        || boot_led_changed
        || triggered_pins_changed
        || wifi_changed
        || ip_changed
        || ap_changed;

    (gpios_to_reset, needs_restart)
}

fn decode_supported_pids(cache: &crate::obd2::SupportedPidsCache) -> Vec<u8> {
    let mut pids = Vec::new();
    for (slot, entry) in cache.entries.iter().enumerate() {
        let Some(raw) = entry else { continue };
        let hex_str: String = raw
            .iter()
            .filter(|b| b.is_ascii_hexdigit())
            .map(|&b| b as char)
            .collect();
        let bytes: Vec<u8> = hex_str
            .as_bytes()
            .chunks(2)
            .filter_map(|chunk| {
                if chunk.len() == 2 {
                    u8::from_str_radix(std::str::from_utf8(chunk).ok()?, 16).ok()
                } else {
                    None
                }
            })
            .collect();
        if bytes.len() < 6 || bytes[0] != 0x41 {
            continue;
        }
        #[allow(clippy::cast_possible_truncation)]
        let base = (slot as u8) * 0x20 + 1;
        for (byte_idx, &byte) in bytes[2..6].iter().enumerate() {
            for bit in 0..8u8 {
                if byte & (0x80 >> bit) != 0 {
                    #[allow(clippy::cast_possible_truncation)]
                    let pid = base + (byte_idx as u8) * 8 + bit;
                    pids.push(pid);
                }
            }
        }
    }
    pids
}

// ── OTA helpers ──────────────────────────────────────────────────────────────

fn perform_ota_reboot(state: &Arc<State>) -> ! {
    std::thread::sleep(std::time::Duration::from_secs(2));
    info!("Stopping WiFi before OTA reboot...");
    if let Ok(mut wifi_guard) = state.wifi.lock() {
        if let Err(e) = wifi_guard.stop() {
            warn!("Failed to stop WiFi: {e:?}");
        }
    }
    info!("Rebooting into new firmware...");
    unsafe {
        esp_idf_svc::sys::esp_restart();
    }
}

fn schedule_ota_reboot(state: Arc<State>) {
    crate::thread_util::spawn_named(
        c"ota-reboot",
        4096,
        crate::thread_util::StackMemory::SpiRam,
        move || {
            perform_ota_reboot(&state);
        },
    );
}

